#!/usr/bin/env python3
"""One Line, One Laugh: Roast Your Fridge.

A tiny program that prints exactly one funny line: the midnight
fridge-opener's lament. No input, no randomness, no extra output.
"""

LINE = (
    "At midnight I open you hoping for a miracle, and you just hum, "
    "glow, and offer a 2019 ketchup and one carrot that filed for retirement."
)


def main() -> None:
    print(LINE)


if __name__ == "__main__":
    main()
